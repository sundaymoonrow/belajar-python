nama = "Budi"
umur = 90
harga = 1598761.98763
print(f"Nama saya {nama}, umur saya {umur} tahun.") # f-String, berfungsi untuk menyisipkan variabel ke dalam teks

print(f"{harga:,}") # :, berguna untuk memisahkan angka yang menyatu, seperti 15000 menjadi 15,000
print(f"{harga:.2f}") # :2f berguna untuk menentukan 2 angka dibelakang koma
print(f"{harga:,.2f}") # Bisa digabungkan
